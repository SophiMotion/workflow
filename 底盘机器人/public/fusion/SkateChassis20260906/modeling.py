"""Native Fusion parametric modeling, called only on Fusion's main thread."""
import adsk.core
import adsk.fusion
import json


def build_model(payload):
    app=adsk.core.Application.get()
    cfg,bodies=payload['config'],payload['bodies']
    doc = app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
    design = adsk.fusion.Design.cast(app.activeProduct)
    design.designType = adsk.fusion.DesignTypes.ParametricDesignType
    root = design.rootComponent
    root.name = 'SkateChassis'
    val = adsk.core.ValueInput.createByString
    point = adsk.core.Point3D.create
    units = design.unitsManager

    for key, field in [('body_length', 'length'), ('body_width', 'width'),
                       ('mast_height', 'mast'), ('wheel_diameter', 'wheel')]:
        design.userParameters.add(key, val(str(cfg[field]) + ' mm'), 'mm',
                                  'SophiStudio primary design parameter')

    for body in bodies:
        name = body['id']
        occurrence = root.occurrences.addNewComponent(adsk.core.Matrix3D.create())
        component = occurrence.component
        component.name = name
        dims = []
        for i, expression in enumerate(body['sizeExpr']):
            pname = name + '_size_' + str(i)
            design.userParameters.add(pname, val(expression), 'mm', 'Geometry dimension')
            dims.append(pname)

        # XY sketches create boxes and vertical cylinders; XZ handles wheel axes.
        horizontal = body['shape'] == 'cylinder' and abs(body['rotation'][0]) > 0.1
        plane = component.xZConstructionPlane if horizontal else component.xYConstructionPlane
        sketch = component.sketches.add(plane)
        sketch.name = name + '_profile'
        if body['shape'] == 'box':
            sx = units.evaluateExpression(dims[0], 'cm')
            sy = units.evaluateExpression(dims[1], 'cm')
            lines = sketch.sketchCurves.sketchLines.addCenterPointRectangle(
                point(0, 0, 0), point(sx / 2, sy / 2, 0))
            # Center point fixed at the component origin; rectangle constraints
            # generated by Fusion preserve symmetry as dimensions change.
            for j in range(sketch.sketchPoints.count):
                p = sketch.sketchPoints.item(j)
                if p.geometry.distanceTo(point(0, 0, 0)) < 1e-7:
                    p.isFixed = True
            horizontal_line = next(lines.item(k) for k in range(4)
                                   if abs(lines.item(k).startSketchPoint.geometry.y - lines.item(k).endSketchPoint.geometry.y) < 1e-7)
            vertical_line = next(lines.item(k) for k in range(4)
                                 if abs(lines.item(k).startSketchPoint.geometry.x - lines.item(k).endSketchPoint.geometry.x) < 1e-7)
            dim = sketch.sketchDimensions.addDistanceDimension(
                horizontal_line.startSketchPoint, horizontal_line.endSketchPoint,
                adsk.fusion.DimensionOrientations.AlignedDimensionOrientation,
                point(0, -sy, 0))
            dim.parameter.expression = dims[0]
            dim2 = sketch.sketchDimensions.addDistanceDimension(
                vertical_line.startSketchPoint, vertical_line.endSketchPoint,
                adsk.fusion.DimensionOrientations.AlignedDimensionOrientation,
                point(sx, 0, 0))
            dim2.parameter.expression = dims[1]
            depth = dims[2]
        else:
            radius = units.evaluateExpression(dims[0], 'cm')
            circle = sketch.sketchCurves.sketchCircles.addByCenterRadius(point(0, 0, 0), radius)
            circle.centerSketchPoint.isFixed = True
            dim = sketch.sketchDimensions.addDiameterDimension(circle, point(radius * 2, 0, 0))
            dim.parameter.expression = dims[0] + ' * 2'
            depth = dims[1]
        ext = component.features.extrudeFeatures
        ext_input = ext.createInput(sketch.profiles.item(0), adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
        ext_input.setSymmetricExtent(val(depth), True)
        feature = ext.add(ext_input)
        feature.name = name + '_extrude'
        feature.bodies.item(0).name = name

        # Root-space joint origins are driven by expressions. All occurrence
        # placement remains editable when chassis dimensions change.
        anchor_input = root.jointOrigins.createInput(
            adsk.fusion.JointGeometry.createByPoint(root.originConstructionPoint))
        anchor = root.jointOrigins.add(anchor_input)
        anchor.name = name + '_location'
        anchor.offsetX.expression = body['positionExpr'][0]
        anchor.offsetY.expression = body['positionExpr'][1]
        anchor.offsetZ.expression = body['positionExpr'][2]
        child_point = component.originConstructionPoint.createForAssemblyContext(occurrence)
        child_geo = adsk.fusion.JointGeometry.createByPoint(child_point)
        joint_input = root.joints.createInput(child_geo, anchor)
        joint_input.setAsRigidJointMotion()
        joint = root.joints.add(joint_input)
        joint.name = name + '_position_joint'
        sketch.isVisible = False
        anchor.isLightBulbOn = False

    design.computeAll()
    app.activeViewport.fit()
    root.attributes.add('SophiStudio', 'configuration', json.dumps(payload, ensure_ascii=False))
    return design


def save_f3d(design):
    app=adsk.core.Application.get()
    dialog=app.userInterface.createFileDialog()
    dialog.title='保存 SkateChassis F3D'
    dialog.filter='Fusion Archive (*.f3d)'
    dialog.initialFilename='SkateChassis.f3d'
    if dialog.showSave()!=adsk.core.DialogResults.DialogOK:
        return None
    destination=dialog.filename
    if not destination.lower().endswith('.f3d'): destination+='.f3d'
    options=design.exportManager.createFusionArchiveExportOptions(destination)
    if not design.exportManager.execute(options): raise RuntimeError('F3D 导出失败，模型仍保留在 Fusion 中。')
    return destination
